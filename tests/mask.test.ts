import { describe, expect, it } from "vitest";

import { mask } from "@/lib/mask";

describe("mask", () => {
  it("금액(12,000,000원 · 1200만원)을 지우지 않는다", () => {
    const text = "예산 12,000,000원, 상한 1200만원, 견적 3,500입니다.";

    expect(mask(text)).toBe(text);
  });

  it("날짜(2026-09-08 · 9월 8일)를 지우지 않는다", () => {
    const text = "2026-09-08, 9/8, 9월 8일입니다.";

    expect(mask(text)).toBe(text);
  });

  it("수량을 지우지 않는다", () => {
    const text = "수량 1200개, 3,500개, 12묶음을 납품합니다.";

    expect(mask(text)).toBe(text);
  });

  it.each([
    "010-1234-5678",
    "01012345678",
    "010 1234 5678",
  ])("휴대폰 번호 %s를 [전화번호]로 바꾼다", (phone) => {
    expect(mask(`연락처는 ${phone}입니다.`)).toBe(
      "연락처는 [전화번호]입니다.",
    );
  });

  it("이메일·주민번호·계좌·카드번호를 종류가 남는 토큰으로 바꾼다", () => {
    const text = [
      "메일 a@b.co.kr",
      "주민번호 123456-1234567",
      "국민 123456-78-901234",
      "카드 1234-5678-9012-3456",
    ].join(" / ");

    expect(mask(text)).toBe(
      "메일 [이메일] / 주민번호 [주민번호] / 국민 [계좌번호] / 카드 [카드번호]",
    );
  });

  it("같은 종류의 개인정보가 여러 번 나와도 모두 마스킹한다", () => {
    expect(mask("a@b.co.kr 또는 c@d.com으로 보내주세요.")).toBe(
      "[이메일] 또는 [이메일]으로 보내주세요.",
    );
  });

  it("계좌번호 표지가 있는 연속 숫자 계좌도 마스킹한다", () => {
    expect(mask("계좌번호: 123456789012로 입금해 주세요.")).toBe(
      "계좌번호: [계좌번호]로 입금해 주세요.",
    );
  });
});
